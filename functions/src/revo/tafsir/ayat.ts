/** The Madani 1405 page an ayah (surah * 1000 + ayah) is on. */
export function pageOfKey(key: number): number {
  let lo = 0;
  let hi = PAGE_STARTS.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (PAGE_STARTS[mid] <= key) lo = mid;
    else hi = mid - 1;
  }
  return lo + 1;
}

/** The pages a span of ayat touches: [start, end) as surah * 1000 + ayah. */
export function pagesOfSpan(start: number, end: number): number[] {
  const first = pageOfKey(start);
  const last = pageOfKey(Math.max(start, end - 1));
  return Array.from({ length: last - first + 1 }, (_, i) => first + i);
}

/** Whether the ayah exists. */
export function isAyah(surah: number, ayah: number): boolean {
  return Number.isInteger(surah) && surah >= 1 && surah <= 114 && Number.isInteger(ayah) && ayah >= 1 && ayah <= AYAH_COUNTS[surah - 1];
}
