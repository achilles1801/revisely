#!/usr/bin/env node
/**
 * Writes functions/src/scenarioQuran.ts: what the test scenarios (functions/src/testScenarios.ts) need of the
 * Qur'an's words to write Recite takes the app can read (word numbers as src/lib/recite/quranWords numbers them,
 * 0..77428 in mushaf order): the words in each verse, each page's first word, the Uthmani text of the verses on the
 * pages the scenarios recite, and a few well-known slips into similar ayat.
 *
 *   node scripts/scenario-quran.js
 *
 * From src/data/quranWords.dat (scripts/build-quran-words.py). src/lib/__tests__/testScenarios.port.test.ts checks
 * the file against it, so run this again when that data or the lists below change.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/quranWords.dat'), 'utf8'));

/** Verses in each surah (Hafs). */
const SURAH_VERSES = [
  7, 286, 200, 176, 120, 165, 206, 75, 129, 109, 123, 111, 43, 52, 99, 128, 111, 110, 98, 135, 112, 78, 118, 64, 77, 227, 93, 88, 69, 60, 34,
  30, 73, 54, 45, 83, 182, 88, 75, 85, 54, 53, 89, 59, 37, 35, 38, 29, 18, 45, 60, 49, 62, 55, 78, 96, 29, 22, 24, 13, 14, 11, 11, 18, 12,
  12, 30, 52, 52, 44, 28, 28, 20, 56, 40, 31, 50, 40, 46, 42, 29, 19, 36, 25, 22, 17, 19, 26, 30, 20, 15, 21, 11, 8, 8, 19, 5, 8, 8, 11, 11,
  8, 3, 9, 5, 4, 7, 3, 6, 3, 5, 4, 5, 6,
];

/** The pages the scenarios recite on (their verses' text is written out). */
const TAKE_PAGES = [2, 3, 5, 6, 8, 9, 42, 293, 294, 295, 296, 301, 302, 440, 441, 442, 531, 532, 533, 534, 535, 562, 563, 564, 582, 583, 585, 587];

/**
 * Slips memorizers make into a similar ayah: the word said wrong (or skipped) and where the reciter went on
 * ([surah, ayah, position], positions from 1).
 */
const SLIPS = [
  { at: [2, 58, 6], kind: 'word', into: [7, 161, 7] },
  { at: [2, 35, 7], kind: 'word', into: [7, 19, 6] },
  { at: [80, 3, 2], kind: 'word', into: [82, 17, 2] },
  { at: [18, 75, 4], kind: 'skipped', into: [18, 72, 4] },
];

if (SURAH_VERSES.reduce((a, b) => a + b, 0) !== data.counts.length) throw new Error('verse counts do not add up');

const verseIndex = new Map();
{
  let v = 0;
  for (let s = 1; s <= 114; s++) for (let a = 1; a <= SURAH_VERSES[s - 1]; a++) verseIndex.set(`${s}:${a}`, v++);
}
const verseStart = [0];
for (const c of data.counts) verseStart.push(verseStart[verseStart.length - 1] + c);
const total = verseStart[verseStart.length - 1];
const pageOfWord = (w) => data.boxes[4 * w];
const pageFirst = [];
for (let w = 0, p = 1; p <= 604; p++) {
  while (pageOfWord(w) < p) w++;
  pageFirst.push(w);
}
pageFirst.push(total);

const wordOf = ([s, a, pos]) => verseStart[verseIndex.get(`${s}:${a}`)] + pos - 1;
const textOf = ([s, a, pos]) => data.uthmani[verseIndex.get(`${s}:${a}`)].split(' ')[pos - 1];

const verseText = {};
for (const p of TAKE_PAGES) {
  for (let s = 1, v = 0; s <= 114; s++) {
    for (let a = 1; a <= SURAH_VERSES[s - 1]; a++, v++) {
      const first = verseStart[v];
      const last = verseStart[v + 1] - 1;
      if (pageOfWord(last) >= p && pageOfWord(first) <= p) verseText[`${s}:${a}`] = data.uthmani[v];
    }
  }
}

const slips = SLIPS.map((s) => ({
  w: wordOf(s.at),
  ayah: [s.at[0], s.at[1]],
  kind: s.kind,
  expected: textOf(s.at),
  heard: s.kind === 'word' ? textOf(s.into) : null,
  into: { w: wordOf(s.into), ayah: [s.into[0], s.into[1]] },
}));

const lines = (nums, per = 30) => {
  const out = [];
  for (let i = 0; i < nums.length; i += per) out.push('  ' + nums.slice(i, i + per).join(', ') + ',');
  return out.join('\n');
};

const src = `/**
 * The Qur'an's words as the test scenarios need them (generated by scripts/scenario-quran.js from
 * src/data/quranWords.dat; don't edit by hand). Word numbers are the app's (src/lib/recite/quranWords: 0..${total - 1}
 * in mushaf order); src/lib/__tests__/testScenarios.port.test.ts checks every table here against the app's data.
 */

/** Verses in each surah. */
export const SURAH_VERSES: readonly number[] = [
${lines(SURAH_VERSES)}
];

/** Words in each verse, in mushaf order (${data.counts.length}). */
export const VERSE_WORDS: readonly number[] = [
${lines(data.counts, 40)}
];

/** The first word of each page (index 0 is page 1); the last entry is the word count. */
export const PAGE_FIRST_WORD: readonly number[] = [
${lines(pageFirst, 15)}
];

/** The pages the scenarios recite on. */
export const TAKE_PAGES: readonly number[] = [${TAKE_PAGES.join(', ')}];

/** The Uthmani text of every verse on TAKE_PAGES ("surah:ayah" → its words, separated by spaces). */
export const VERSE_TEXT: Readonly<Record<string, string>> = ${JSON.stringify(verseText, null, 2)};

/** Well-known slips into a similar ayah: the word, what was said instead, and where the reciter went on. */
export const SLIPS: readonly {
  w: number;
  ayah: [number, number];
  kind: 'word' | 'skipped';
  expected: string;
  heard: string | null;
  into: { w: number; ayah: [number, number] };
}[] = ${JSON.stringify(slips, null, 2)};
`;

fs.writeFileSync(path.join(ROOT, 'functions/src/scenarioQuran.ts'), src);
console.log(`functions/src/scenarioQuran.ts: ${Object.keys(verseText).length} verses of text, ${slips.length} slips, ${(src.length / 1024).toFixed(0)} KB`);
